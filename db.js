const { Pool } = require("pg");

const pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: process.env.DATABASE_SSL === "false" ? false : { rejectUnauthorized: false }
});

function prepareQuery(text, values) {
    let index = 0;
    const queryText = text.replace(/\?/g, () => `$${++index}`);
    return { text: queryText, values };
}

async function query(text, values = []) {
    return pool.query(prepareQuery(text, values));
}

const database = {
    async get(text, values = []) {
        const result = await query(text, values);
        return result.rows[0];
    },
    async all(text, values = []) {
        const result = await query(text, values);
        return result.rows;
    },
    async run(text, values = []) {
        const result = await query(text, values);
        return { changes: result.rowCount || 0, recordset: result.rows };
    },
    async exec(text) {
        return query(text);
    },
    async init() {
        await query(`
            CREATE TABLE IF NOT EXISTS usuarios (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre VARCHAR(80) NOT NULL,
                usuario VARCHAR(30) NOT NULL UNIQUE,
                correo VARCHAR(120) NOT NULL UNIQUE,
                telefono VARCHAR(30) NOT NULL,
                nacionalidad VARCHAR(80) NOT NULL,
                password_hash VARCHAR(200) NOT NULL,
                creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
            );
            CREATE TABLE IF NOT EXISTS sesiones (
                token_hash CHAR(64) PRIMARY KEY,
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
                expira_en TIMESTAMPTZ NOT NULL
            );
            CREATE TABLE IF NOT EXISTS movimientos (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
                tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('ingreso', 'gasto')),
                categoria VARCHAR(80) NOT NULL,
                monto NUMERIC(18, 2) NOT NULL CHECK (monto >= 0),
                fecha DATE NOT NULL,
                creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
            );
            CREATE TABLE IF NOT EXISTS metas_ahorro (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
                nombre VARCHAR(120) NOT NULL,
                monto_objetivo NUMERIC(18, 2) NOT NULL CHECK (monto_objetivo > 0),
                monto_actual NUMERIC(18, 2) NOT NULL DEFAULT 0 CHECK (monto_actual >= 0),
                fecha_objetivo DATE NULL,
                creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
            );
            CREATE TABLE IF NOT EXISTS tarjetas_control (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
                alias VARCHAR(80) NOT NULL,
                entidad VARCHAR(80) NULL,
                limite NUMERIC(18, 2) NOT NULL DEFAULT 0 CHECK (limite >= 0),
                dia_corte SMALLINT NOT NULL CHECK (dia_corte BETWEEN 1 AND 31),
                dia_pago SMALLINT NOT NULL CHECK (dia_pago BETWEEN 1 AND 31),
                creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
            );
            CREATE TABLE IF NOT EXISTS paises (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre VARCHAR(80) NOT NULL UNIQUE
            );
        `);
        const paises = ["Argentina", "Bolivia", "Brasil", "Canadá", "Chile", "Colombia", "Costa Rica", "Cuba", "Ecuador", "El Salvador", "España", "Estados Unidos", "Guatemala", "Honduras", "México", "Nicaragua", "Panamá", "Paraguay", "Perú", "Puerto Rico", "República Dominicana", "Uruguay", "Venezuela", "Alemania", "Australia", "China", "Corea del Sur", "Egipto", "Francia", "India", "Indonesia", "Italia", "Japón", "Marruecos", "Noruega", "Nueva Zelanda", "Países Bajos", "Portugal", "Reino Unido", "Rusia", "Sudáfrica", "Suecia", "Suiza", "Turquía"];
        for (const pais of paises) {
            await query("INSERT INTO paises (nombre) VALUES (?) ON CONFLICT (nombre) DO NOTHING", [pais]);
        }
    }
};

module.exports = database;
